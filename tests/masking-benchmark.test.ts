/**
 * Masking benchmark on the DEVELOPMENT split only (evaluation/masking/dev).
 * Pins the recorded per-category result so any detector change must be
 * re-measured with `npx tsx evaluation/masking/evaluate-dev.ts` and the new
 * result committed. The locked held-out split is never read here; the last
 * case checks that no test, source or evaluation file other than the one
 * held-out script refers to its file.
 */
import { readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import {
  isValidCardNumber,
  isValidGermanTaxId,
  isValidIban,
} from "../src/identifier-masking";
import {
  type Corpus,
  DEV_PER_CATEGORY,
  DEV_SEED,
  generateSplit,
  serializeCorpus,
} from "../evaluation/masking/corpus";
import { CATEGORIES } from "../evaluation/masking/layouts";
import { type BenchmarkResult, evaluate, wilson } from "../evaluation/masking/score";

const root = join(__dirname, "..");
const devBytes = readFileSync(join(root, "evaluation/masking/dev/dev.json"), "utf8").replace(/\r\n/g, "\n");
const dev = JSON.parse(devBytes) as Corpus;
const recorded = JSON.parse(
  readFileSync(join(root, "evaluation/masking/results/dev-current.json"), "utf8"),
) as BenchmarkResult;

describe("masking benchmark, development split", () => {
  it("is regenerated byte for byte from its seed", () => {
    expect(serializeCorpus(generateSplit("dev", DEV_SEED, DEV_PER_CATEGORY))).toBe(devBytes);
  });

  it("has well over ten samples per category and consistent ground truth", () => {
    for (const category of CATEGORIES) {
      const samples = dev.samples.filter((s) => s.category === category);
      expect(samples.length, category).toBeGreaterThanOrEqual(50);
    }
    for (const sample of dev.samples) {
      expect(sample.spans.length, sample.id).toBeGreaterThan(0);
      const sorted = [...sample.spans].sort((a, b) => a.start - b.start);
      sorted.forEach((span, i) => {
        expect(span.end).toBeLessThanOrEqual(sample.text.length);
        if (i) expect(span.start, sample.id).toBeGreaterThanOrEqual(sorted[i - 1].end);
      });
      if (sample.ocr) continue;
      for (const span of sample.spans) {
        const value = sample.text.slice(span.start, span.end).replace(/[\s​‌­﻿]/g, "");
        if (span.kind === "IBAN") expect(isValidIban(value), `${sample.id} ${value}`).toBe(true);
        if (span.kind === "CARD") expect(isValidCardNumber(value), `${sample.id} ${value}`).toBe(true);
        if (span.variant.startsWith("taxid:"))
          expect(isValidGermanTaxId(value), `${sample.id} ${value}`).toBe(true);
      }
    }
  });

  it("reproduces the recorded per-category and per-kind result", () => {
    const result = evaluate(dev, recorded.label, recorded.corpusSha256);
    expect(result.overall).toEqual(recorded.overall);
    expect(result.byCategory).toEqual(recorded.byCategory);
    expect(result.byKind).toEqual(recorded.byKind);
    expect(result.misses.length).toBe(recorded.misses.length);
    expect(result.falsePositives.length).toBe(recorded.falsePositives.length);
  });

  it("computes Wilson intervals", () => {
    expect(wilson(0, 0)).toBeNull();
    expect(wilson(50, 100)).toEqual([0.4038, 0.5962]);
    expect(wilson(10, 10)![1]).toBe(1);
  });

  it("is the only split any test or tuning file reads", () => {
    const name = "held" + "out";
    const lockedFile = new RegExp(
      `${name}[/\\\\]${name}\\.json|masking[/\\\\]${name}`,
    );
    const allowed = new Set([
      "evaluation/masking/evaluate-held" + "out.ts",
      "evaluation/masking/write-held" + "out.ts",
    ]);
    const offenders: string[] = [];
    const walk = (dir: string) => {
      for (const entry of readdirSync(join(root, dir), { withFileTypes: true })) {
        const path = `${dir}/${entry.name}`;
        if (entry.isDirectory()) {
          if (!["node_modules", "results", "dev"].includes(entry.name)) walk(path);
        } else if (/\.(ts|tsx|mjs|js)$/.test(entry.name) && !allowed.has(path)) {
          if (lockedFile.test(readFileSync(join(root, path), "utf8"))) offenders.push(path);
        }
      }
    };
    for (const dir of ["src", "tests", "evaluation", "scripts", "server", "shared"]) walk(dir);
    expect(offenders).toEqual([]);
  });
});
